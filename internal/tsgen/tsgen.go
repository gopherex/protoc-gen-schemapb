// Package tsgen emits the TypeScript code of protoc-gen-ts-schemapb: for
// every message, a Validator over the protobuf-es descriptor and the
// embedded schema, backed by the @gopherex/schemapb runtime.
package tsgen

import (
	"encoding/base64"
	"errors"
	"fmt"
	"path"
	"slices"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"

	"github.com/gopherex/protoc-gen-schemapb/internal/frontend"
)

// ErrParameter reports an invalid plugin parameter.
var ErrParameter = errors.New("invalid parameter")

// Options are the plugin parameters.
type Options struct {
	// ImportExtension is appended to relative imports: "none" (default, as
	// protoc-gen-es), "js" or "ts".
	ImportExtension string
	// RuntimeModule is the module the Validator is imported from.
	RuntimeModule string
}

// Set applies one plugin parameter.
func (o *Options) Set(name, value string) error {
	switch name {
	case "import_extension":
		switch strings.TrimPrefix(value, ".") {
		case "", "none":
			o.ImportExtension = ""
		case "js", "ts":
			o.ImportExtension = "." + strings.TrimPrefix(value, ".")
		default:
			return fmt.Errorf("%w: import_extension: want none, js or ts, got %q", ErrParameter, value)
		}
	case "runtime_module":
		o.RuntimeModule = value
	case "target":
		if value != "ts" {
			return fmt.Errorf("%w: target: only ts is supported, got %q", ErrParameter, value)
		}
	default:
		return fmt.Errorf("%w: unknown parameter %q", ErrParameter, name)
	}

	return nil
}

// GenerateFile emits <name>_schemapb.ts next to protoc-gen-es's <name>_pb.ts,
// or nothing when no message of the file gets a validator.
func GenerateFile(plugin *protogen.Plugin, file *protogen.File, opts Options) error {
	messages := collect(file.Messages)
	if len(messages) == 0 {
		return nil
	}

	runtime := opts.RuntimeModule
	if runtime == "" {
		runtime = "@gopherex/schemapb"
	}

	names := descNames(file.Desc)
	base := strings.TrimSuffix(path.Base(file.Desc.Path()), ".proto")

	type entry struct {
		validator, desc, full, raw string
	}

	entries := make([]entry, 0, len(messages))
	imports := make([]string, 0, len(messages))

	for _, msg := range messages {
		schema, err := frontend.Schema(msg)
		if err != nil {
			return fmt.Errorf("tsgen: %w", err)
		}

		raw, err := proto.MarshalOptions{Deterministic: true}.Marshal(schema)
		if err != nil {
			return fmt.Errorf("tsgen: encode schema of %s: %w", msg.Desc.FullName(), err)
		}

		desc := names[msg.Desc.FullName()]
		entries = append(entries, entry{
			validator: safeIdentifier(identifier(file.Desc, msg.Desc) + "Validator"),
			desc:      desc,
			full:      string(msg.Desc.FullName()),
			raw:       base64.StdEncoding.EncodeToString(raw),
		})
		imports = append(imports, desc)
	}

	slices.Sort(imports)

	g := plugin.NewGeneratedFile(strings.TrimSuffix(file.Desc.Path(), ".proto")+"_schemapb.ts", "")
	g.P("// @generated by protoc-gen-ts-schemapb. DO NOT EDIT.")
	g.P("// source: ", file.Desc.Path())
	g.P()
	g.P(`import { Validator } from "`, runtime, `";`)
	g.P("import { ", strings.Join(imports, ", "), ` } from "./`, base, "_pb", opts.ImportExtension, `";`)

	for _, e := range entries {
		g.P()
		g.P("/**")
		g.P(" * Validator of ", e.full, ".")
		g.P(" */")
		g.P("export const ", e.validator, " = /*@__PURE__*/ new Validator(")
		g.P("  ", e.desc, ",")
		g.P(`  "`, e.raw, `",`)
		g.P(");")
	}

	return nil
}

func collect(messages []*protogen.Message) []*protogen.Message {
	var out []*protogen.Message

	for _, msg := range messages {
		if !frontend.Skipped(msg) {
			out = append(out, msg)
		}

		out = append(out, collect(msg.Messages)...)
	}

	return out
}
