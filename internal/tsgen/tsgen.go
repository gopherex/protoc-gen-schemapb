// Package tsgen emits the TypeScript code of protoc-gen-ts-schemapb: for
// every message, a Validator over the protobuf-es descriptor and the
// embedded schema, backed by the @gopherex/schemapb runtime.
package tsgen

import (
	"encoding/base64"
	"errors"
	"fmt"
	"path/filepath"
	"slices"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protoreflect"

	"github.com/gopherex/protoc-gen-schemapb/internal/frontend"
)

// ErrParameter reports an invalid plugin parameter.
var ErrParameter = errors.New("invalid parameter")

// Options are the plugin parameters.
type Options struct {
	// ImportExtension is appended to relative imports: "none" (default, as
	// protoc-gen-es), "js" or "ts".
	ImportExtension string
	// RuntimeModule is the module the Validator is imported from.
	RuntimeModule string
	// Targets are the outputs, as protoc-gen-es: "ts" (default), "js",
	// "dts", combined with "+".
	Targets []string
}

// Set applies one plugin parameter.
func (o *Options) Set(name, value string) error {
	switch name {
	case "import_extension":
		switch strings.TrimPrefix(value, ".") {
		case "", "none":
			o.ImportExtension = ""
		case "js", "ts":
			o.ImportExtension = "." + strings.TrimPrefix(value, ".")
		default:
			return fmt.Errorf("%w: import_extension: want none, js or ts, got %q", ErrParameter, value)
		}
	case "runtime_module":
		o.RuntimeModule = value
	case "target":
		o.Targets = nil

		for _, t := range strings.Split(value, "+") {
			if t != "ts" && t != "js" && t != "dts" {
				return fmt.Errorf("%w: target: want ts, js, dts or a + combination, got %q", ErrParameter, value)
			}

			o.Targets = append(o.Targets, t)
		}
	default:
		return fmt.Errorf("%w: unknown parameter %q", ErrParameter, name)
	}

	return nil
}

type entry struct {
	validator, desc, full, raw string
	anyTypes                   []string // descriptor identifiers
}

// GenerateFile emits <name>_schemapb.ts (and/or .js, .d.ts) next to
// protoc-gen-es's <name>_pb.*, or nothing when no message of the file gets
// a validator.
func GenerateFile(plugin *protogen.Plugin, file *protogen.File, opts Options) error {
	messages := collect(file.Messages)
	if len(messages) == 0 {
		return nil
	}

	runtime := opts.RuntimeModule
	if runtime == "" {
		runtime = "@gopherex/schemapb"
	}

	targets := opts.Targets
	if len(targets) == 0 {
		targets = []string{"ts"}
	}

	fe := frontend.New(plugin)
	imports := newImports(file.Desc.Path())
	entries := make([]entry, 0, len(messages))

	for _, msg := range messages {
		e, err := buildEntry(fe, imports, msg)
		if err != nil {
			return err
		}

		entries = append(entries, e)
	}

	base := strings.TrimSuffix(file.Desc.Path(), ".proto")

	for _, target := range targets {
		suffix := map[string]string{"ts": ".ts", "js": ".js", "dts": ".d.ts"}[target]
		g := plugin.NewGeneratedFile(base+"_schemapb"+suffix, "")
		emit(g, file, runtime, opts.ImportExtension, target == "dts", imports, entries)
	}

	return nil
}

func buildEntry(fe frontend.Frontend, imports *imports, msg *protogen.Message) (entry, error) {
	built, err := fe.Schema(msg)
	if err != nil {
		return entry{}, fmt.Errorf("tsgen: %w", err)
	}

	raw, err := proto.MarshalOptions{Deterministic: true}.Marshal(built.Schema)
	if err != nil {
		return entry{}, fmt.Errorf("tsgen: encode schema of %s: %w", msg.Desc.FullName(), err)
	}

	desc := imports.add(msg.Desc)
	e := entry{
		validator: validatorName(desc),
		desc:      desc,
		full:      string(msg.Desc.FullName()),
		raw:       base64.StdEncoding.EncodeToString(raw),
	}

	for _, t := range built.AnyTypes {
		e.anyTypes = append(e.anyTypes, imports.add(t.Desc))
	}

	return e, nil
}

func emit(g *protogen.GeneratedFile, file *protogen.File, runtime, ext string, dts bool,
	imports *imports, entries []entry,
) {
	keyword := "import"
	if dts {
		keyword = "import type"
	}

	g.P("// @generated by protoc-gen-ts-schemapb. DO NOT EDIT.")
	g.P("// source: ", file.Desc.Path())
	g.P()
	g.P(keyword, ` { Validator } from "`, runtime, `";`)

	for _, path := range imports.paths() {
		g.P(keyword, " { ", strings.Join(imports.names(path), ", "), ` } from "`, path, ext, `";`)
	}

	for _, e := range entries {
		g.P()
		g.P("/**")
		g.P(" * Validator of ", e.full, ".")
		g.P(" */")

		if dts {
			g.P("export declare const ", e.validator, ": Validator<typeof ", e.desc, ">;")

			continue
		}

		g.P("export const ", e.validator, " = /*@__PURE__*/ new Validator(")
		g.P("  ", e.desc, ",")
		g.P(`  "`, e.raw, `",`)

		if len(e.anyTypes) > 0 {
			g.P("  [", strings.Join(e.anyTypes, ", "), "],")
		}

		g.P(");")
	}
}

// imports collects the protobuf-es descriptors the generated file needs,
// keyed by the relative module of their _pb file.
type imports struct {
	from   string // proto path of the generating file
	byPath map[string]map[string]bool
	idents map[protoreflect.FileDescriptor]map[protoreflect.FullName]string
}

func newImports(from string) *imports {
	return &imports{
		from:   from,
		byPath: map[string]map[string]bool{},
		idents: map[protoreflect.FileDescriptor]map[protoreflect.FullName]string{},
	}
}

// add records the descriptor of msg and returns its identifier.
func (im *imports) add(msg protoreflect.MessageDescriptor) string {
	file := msg.ParentFile()

	names, ok := im.idents[file]
	if !ok {
		names = descNames(file)
		im.idents[file] = names
	}

	path := relativeModule(im.from, file.Path())
	if im.byPath[path] == nil {
		im.byPath[path] = map[string]bool{}
	}

	name := names[msg.FullName()]
	im.byPath[path][name] = true

	return name
}

func (im *imports) paths() []string {
	out := make([]string, 0, len(im.byPath))
	for p := range im.byPath {
		out = append(out, p)
	}

	slices.Sort(out)

	return out
}

func (im *imports) names(path string) []string {
	out := make([]string, 0, len(im.byPath[path]))
	for n := range im.byPath[path] {
		out = append(out, n)
	}

	slices.Sort(out)

	return out
}

// relativeModule is the import path (without extension) of target's _pb
// module from the file generated for from.
func relativeModule(from, target string) string {
	rel, err := filepath.Rel(filepath.Dir(filepath.FromSlash(from)), filepath.FromSlash(target))
	if err != nil {
		rel = target
	}

	rel = filepath.ToSlash(strings.TrimSuffix(rel, ".proto")) + "_pb"
	if !strings.HasPrefix(rel, "../") {
		rel = "./" + rel
	}

	return rel
}

// validatorName mirrors the descriptor name, so clashes resolved by
// protobuf-es ("Foo_BarSchema$") resolve the same way ("Foo_BarValidator$").
func validatorName(desc string) string {
	i := strings.LastIndex(desc, "Schema")

	return desc[:i] + "Validator" + desc[i+len("Schema"):]
}

func collect(messages []*protogen.Message) []*protogen.Message {
	var out []*protogen.Message

	for _, msg := range messages {
		if !frontend.Skipped(msg) {
			out = append(out, msg)
		}

		out = append(out, collect(msg.Messages)...)
	}

	return out
}
